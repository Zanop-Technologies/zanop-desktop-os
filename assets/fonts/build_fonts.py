#!/usr/bin/env python3
"""
Rasterizes the desktop fonts into compact, legible pixel glyphs and writes
them into a single generated header.

  assets/fonts/Ubuntu-Regular.ttf     -> Ubuntu (legacy UI face)
  assets/fonts/UbuntuMono-Regular.ttf -> Ubuntu Mono (terminal)
  assets/fonts/MONO.ttf               -> Space Mono (default UI)
  assets/fonts/WOBBLYDOODLE.ttf       -> Wobblydoodle (legacy)

Requires: pip install Pillow

Usage:
    python3 assets/fonts/build_fonts.py [output.hpp]

Design notes
------------
The compositor uses 8x12 glyphs: each glyph is column-major (one byte per
column, bit N is row N), with a 9-pixel advance. A taller cell preserves
Ubuntu's letterforms and leaves room for lowercase x-height, accents and
descenders. Glyphs share baseline metrics and retain their natural proportions.
Oversampling and a stroke-aware downsample keep thin strokes visible.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT_DIR = ROOT / "assets" / "fonts"
OUTPUT = ROOT / "compositor" / "src" / "embedded_fonts.hpp"

GLYPH_W = 8
GLYPH_H = 12
FIRST_CODEPOINT = 32  # space
LAST_CODEPOINT = 126  # ~

# Supersample large, then shrink. At this target size, preserve partial
# coverage as a pixel rather than dropping antialiased thin strokes.
SUPERSAMPLE = 4

# Symbol name, file, display name. Order matters only for readability:
# surface::Font maps its enum onto these by name.
#
#   MONO.ttf            -> the default GUI face (surface::Font::Mono)
#   Ubuntu-Regular      -> an alternate UI face (surface::Font::Ui)
#   UbuntuMono-Regular  -> the Terminal face (surface::Font::Terminal)
#   WOBBLYDOODLE.ttf    -> the Wobbly heading/wordmark face.
FONTS = (
    ("Ubuntu-Regular.ttf", "Ubuntu", "Ubuntu"),
    ("UbuntuMono-Regular.ttf", "UbuntuMono", "Ubuntu Mono"),
    ("MONO.ttf", "SpaceMono", "Space Mono"),
    ("WOBBLYDOODLE.ttf", "WobblyDoodle", "Zanop Wobblydoodle"),
)


def rasterize(font, codepoint, top, bottom, cell_width):
    """Return a baseline-aligned glyph packed column-major."""
    char = chr(codepoint)
    if char == " ":
        return [0] * GLYPH_W
    left, _, right, _ = font.getbbox(char)
    canvas = Image.new("L", (cell_width, bottom - top), 0)
    draw = ImageDraw.Draw(canvas)
    draw.text(((cell_width - (right - left)) // 2 - left, -top),
              char, font=font, fill=255)

    # Fit proportionally into the cell, leaving a clear one-pixel border.
    ink = canvas.getbbox()
    if ink is None:
        return [0] * GLYPH_W
    glyph = canvas.crop(ink)
    target_w, target_h = GLYPH_W - 2, GLYPH_H - 2
    factor = min(target_w / glyph.width, target_h / glyph.height)
    resized = glyph.resize((max(1, round(glyph.width * factor)),
                            max(1, round(glyph.height * factor))),
                           Image.Resampling.LANCZOS)
    fitted = Image.new("L", (GLYPH_W, GLYPH_H), 0)
    fitted.paste(resized, ((GLYPH_W - resized.width) // 2,
                           (GLYPH_H - resized.height) // 2))

    columns = []
    for column in range(GLYPH_W):
        bits = 0
        for row in range(GLYPH_H):
            # Retain antialiased hairlines in the final 1-bit mask; the
            # previous threshold caused regular strokes to disappear.
            if fitted.getpixel((column, row)) >= 24:
                bits |= 1 << row
        columns.append(bits & 0xFF)
    return columns


def render_font(ttf_path):
    font = ImageFont.truetype(str(ttf_path), GLYPH_H * SUPERSAMPLE)
    # Use face-wide vertical metrics so lowercase, caps and descenders share
    # a baseline instead of independently stretching to fill the cell.
    ascent, descent = font.getmetrics()
    top = -ascent
    bottom = descent
    cell_width = max(font.getbbox(chr(c))[2] - font.getbbox(chr(c))[0]
                     for c in range(FIRST_CODEPOINT, LAST_CODEPOINT + 1)) + 2
    glyphs = []
    for codepoint in range(FIRST_CODEPOINT, LAST_CODEPOINT + 1):
        rows = rasterize(font, codepoint, top, bottom, cell_width)
        glyphs.append(", ".join(f"0x{byte:02X}" for byte in rows))
    return glyphs


def main():
    if len(sys.argv) > 1:
        out_path = Path(sys.argv[1])
    else:
        out_path = OUTPUT

    lines = [
        "#pragma once",
        "",
        "// Auto-generated by assets/fonts/build_fonts.py -- do not hand-edit.",
        "// Regenerate from the TTFs in assets/fonts/ instead.",
        "//",
        "// 8x12 glyphs, column-major: 8 bytes per glyph, bit N of each byte",
        "// is the pixel in row N (row 0 = top).",
        f"// Covers ASCII {FIRST_CODEPOINT}-{LAST_CODEPOINT}.",
        "",
        "namespace fonts {",
        "",
        f"constexpr unsigned char GLYPH_WIDTH = {GLYPH_W};",
        f"constexpr unsigned char GLYPH_HEIGHT = {GLYPH_H};",
        f"constexpr unsigned char FIRST_GLYPH = {FIRST_CODEPOINT};",
        f"constexpr unsigned char GLYPH_COUNT = {LAST_CODEPOINT - FIRST_CODEPOINT + 1};",
        "constexpr unsigned char ADVANCE = 9;  // glyph width + 1 pixel of spacing",
        "",
    ]

    for filename, symbol, name in FONTS:
        glyphs = render_font(FONT_DIR / filename)
        lines.append(f"// {name} ({filename})")
        lines.append(f"inline constexpr unsigned char {symbol}[][GLYPH_WIDTH] = {{")
        for index, row in enumerate(glyphs):
            lines.append(f"    {{{row}}}, // {FIRST_CODEPOINT + index} "
                         f"{chr(FIRST_CODEPOINT + index)!r}")
        lines.append("};")
        lines.append("")

    lines.append("}  // namespace fonts")
    out_path.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()